import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
// @ts-expect-error — repository governance helper is shipped as JavaScript.
import { readPinnedPiIdentity } from "../governance/pinned-pi-identity.mjs";
import { foregroundAnsi } from "@earendil-works/pi-tui";
import { derivePiAccentProjection, namedPiAccent } from "../../src/integrations/pi/components/upstream/theme/theme.js";
import type { UiAccentColor } from "../../src/contracts/owned-ui/index.js";

const repository = fileURLToPath(new URL("../..", import.meta.url));
const targets = [
  resolve(repository, "src/foundation/release/progress-palette.generated.ts"),
  resolve(repository, "src/ui/settings/progress-palette.generated.ts"),
  resolve(repository, "packages/a1-install/bin/progress-palette.js"),
] as const;
const pinned = await readPinnedPiIdentity(repository) as { readonly version: string; readonly commit: string };
const colors: readonly UiAccentColor[] = ["blue", "purple", "cyan", "green", "orange", "pink"];
const palette = Object.fromEntries(colors.map(color => [color, Object.fromEntries(
  (["dark", "light"] as const).map(appearance => [appearance, Object.fromEntries(
    (["truecolor", "256color"] as const).map(mode => {
      const projection = derivePiAccentProjection(namedPiAccent(color, appearance), appearance);
      return [mode, { accent: foregroundAnsi(projection.accent, mode), border: foregroundAnsi(projection.border, mode) }];
    }),
  )]),
)]));
const source = `/**\n * Generated by scripts/pi/sync-progress-palette.ts from A1's named accent projection\n * over pinned Pi ${pinned.version} (MIT), commit ${pinned.commit}. Do not edit directly.\n */\nexport const SHARED_PROGRESS_PALETTE = Object.freeze(${JSON.stringify(palette, null, 2)});\nexport const SHARED_PROGRESS_ACCENT_ANSI = SHARED_PROGRESS_PALETTE.blue.dark.truecolor.accent;\n`;

if (process.argv.includes("--check")) {
  const stale: string[] = [];
  for (const path of targets) {
    const actual = await readFile(path, "utf8").catch(() => "");
    if (actual !== source) stale.push(path);
  }
  if (stale.length > 0) throw new Error(`progress palette is stale: ${stale.join(", ")}`);
  process.stdout.write("Progress palette matches the named A1 accents.\n");
} else {
  await Promise.all(targets.map(async path => await writeFile(path, source)));
  process.stdout.write(`Updated A1 progress palette over Pi ${pinned.version}.\n`);
}
